/** 插件追加的词条层（后加的先查）；内置词典永远优先，插件不能改写已有文案 */
const EXTRA: Array<{ lang: string; dict: Record<string, string> }> = [];

export function extendDict(lang: string, dict: Record<string, string>): () => void {
  const layer = { lang, dict };
  EXTRA.unshift(layer);
  return () => {
    const i = EXTRA.indexOf(layer);
    if (i >= 0) EXTRA.splice(i, 1);
  };
}

const extra = (lang: string, key: string) => {
  for (const l of EXTRA) if (l.lang === lang && key in l.dict) return l.dict[key];
  return undefined;
};

export function hasText(key: string): boolean {
  const lang = getLang();
  return key in DICT[lang] || key in DICT.en || extra(lang, key) !== undefined || extra("en", key) !== undefined;
}

export function et(key: string, params?: Record<string, string | number>): string {
  const lang = getLang();
  const raw = DICT[lang][key] ?? extra(lang, key) ?? DICT.en[key] ?? extra("en", key) ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
}

export function applyEditorStatic(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>("[data-et]")) el.textContent = et(el.dataset.et!);
  for (const el of root.querySelectorAll<HTMLElement>("[data-et-title]")) el.title = et(el.dataset.etTitle!);
  for (const el of root.querySelectorAll<HTMLElement>("[data-et-ph]")) {
    (el as HTMLInputElement).placeholder = et(el.dataset.etPh!);
  }
}

onChangeLang(() => applyEditorStatic());
