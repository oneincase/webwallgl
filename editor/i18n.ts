export function et(key: string, params?: Record<string, string | number>): string {
  const raw = DICT[getLang()][key] ?? DICT.en[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
}

export function applyEditorStatic(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>("[data-et]")) el.textContent = et(el.dataset.et!);
  for (const el of root.querySelectorAll<HTMLElement>("[data-et-title]")) el.title = et(el.dataset.etTitle!);
  for (const el of root.querySelectorAll<HTMLElement>("[data-et-ph]")) {
    (el as HTMLInputElement).placeholder = et(el.dataset.etPh!);
  }
}

onChangeLang(() => applyEditorStatic());
